  <h2>3. Defects, non-conformity and legal warranties</h2>
  <p>If your card has a manufacturing defect, a faulty NFC chip, a QR code that does not work or a significant difference from the agreed order, contact us with a description of the problem. We will review it and offer the appropriate solution, which may include a correction, replacement or refund.</p>
  <p class="callout"><strong>Important:</strong> legal warranties apply regardless of this policy. A request made after 30 days is not automatically excluded from the rights provided by law.</p>

  <h2>4. Cancellation and change of mind</h2>
  <h3>Before production starts</h3>
  <p>Contact us quickly with your order reference. We will check whether production or custom work has begun and tell you the terms that apply to your order.</p>
  <h3>After production starts</h3>
  <p>Cancelling for a simple change of mind may not lead to a refund if custom manufacturing is under way. Every request is still reviewed against the agreement and applicable legal rules.</p>
  <h3>Cancellations provided by law</h3>
  <p>For certain distance contracts (online or by phone), the law lets consumers cancel in specific circumstances, for example when the merchant does not meet certain information or delivery obligations. These rights apply even if our commercial policy is more restrictive.</p>

  <h2>5. Delivery, loss and returns</h2>
  <p>Manufacturing and delivery times are those communicated and agreed for your order. If your order is late or does not arrive, write to us so we can check its status and find a suitable solution. If a physical return is needed to assess a problem, we will send instructions before anything is shipped; return costs are handled according to the law and the nature of the problem.</p>

  <h2>6. How to make a request</h2>
  <ol>
    <li>Write to <a href="mailto:info@elitetap.ca">info@elitetap.ca</a> with the subject of your request (defect, cancellation, delivery or other).</li>
    <li>Include your name, the order details and the date you received it, if applicable.</li>
    <li>If possible, attach photos or a short video showing the problem.</li>
    <li>We will acknowledge your request and tell you the next steps within a reasonable time.</li>
  </ol>

  <h2>7. How refunds are processed</h2>
  <p>When a refund is granted, the method and timing are communicated based on the original payment and applicable obligations. When a distance contract is cancelled under the Consumer Protection Act, refundable amounts must be paid within the legal deadline, generally within 15 days of cancellation. An EliteTap credit does not replace a refund the consumer is legally entitled to, unless the law allows this choice and the consumer validly agrees.</p>

