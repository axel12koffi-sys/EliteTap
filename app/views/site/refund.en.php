  <h2>1. Custom orders</h2>
  <p>EliteTap NFC cards can be made with a logo, name, contact details, design, materials and finishes chosen by the client. We may send a mock-up or proof for approval before production.</p>
  <p>For a simple change of mind, a card that has been customized or put into production is generally neither exchangeable nor refundable under our commercial policy, subject to the rights provided by law.</p>
  <p>Before approving the mock-up, please check the text, contact details, colours and other custom elements. This check does not remove your remedies in case of a defect, non-conformity or error attributable to EliteTap.</p>

